-- Everything the enrolment screen has to know about one student, in one call.
CREATE OR REPLACE FUNCTION student_eligible_subjects(p_user_id INTEGER, p_semester_id INTEGER)
    RETURNS TABLE (
        subject_id        INTEGER,
        subject_code      VARCHAR,
        subject_name      VARCHAR,
        awarded_credits   INTEGER,
        already_passed    BOOLEAN,
        prerequisites_ok  BOOLEAN,
        has_professor     BOOLEAN
    )
    LANGUAGE sql STABLE
AS $$
    SELECT s.id,
           s.code,
           s.name,
           s.awarded_credits::INTEGER,
           EXISTS (SELECT 1
                     FROM passed_subjects ps
                     JOIN semesters_subjects ss2 ON ss2.id = ps.enrolled_id
                     JOIN enrolled_semesters es2 ON es2.id = ss2.enrolled_semesters_id
                    WHERE es2.user_id = p_user_id AND ss2.subjects_id = s.id),
           NOT EXISTS (SELECT 1
                         FROM dependency_subject d
                        WHERE d.subject_id = s.id
                          AND NOT EXISTS (
                              SELECT 1
                                FROM passed_subjects ps
                                JOIN semesters_subjects ss3 ON ss3.id = ps.enrolled_id
                                JOIN enrolled_semesters es3 ON es3.id = ss3.enrolled_semesters_id
                               WHERE es3.user_id = p_user_id
                                 AND ss3.subjects_id = d.dependency_id)),
           EXISTS (SELECT 1 FROM professour_subjects pr
                    WHERE pr.subject_id = s.id AND pr.active_semester_id = p_semester_id)
    FROM subjects s
    WHERE EXISTS (
        SELECT 1
          FROM major_subjects ms
          JOIN enrolled_semesters es ON es.major_id = ms.major_id
         WHERE ms.subject_id = s.id AND es.user_id = p_user_id)
    ORDER BY s.code;
$$;

-- Average grade and credits of a student, as one row.
CREATE OR REPLACE FUNCTION student_summary(p_user_id INTEGER)
    RETURNS TABLE (passed_subjects BIGINT, credits BIGINT, average_grade NUMERIC)
    LANGUAGE sql STABLE
AS $$
    SELECT count(ps.id),
           coalesce(sum(s.awarded_credits), 0)::BIGINT,
           round(avg(ps.grade::TEXT::INT)::NUMERIC, 2)
    FROM passed_subjects ps
    JOIN semesters_subjects ss ON ss.id = ps.enrolled_id
    JOIN enrolled_semesters es ON es.id = ss.enrolled_semesters_id
    JOIN subjects s            ON s.id  = ss.subjects_id
    WHERE es.user_id = p_user_id;
$$;

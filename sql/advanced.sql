-- Marks an enrolment finished once every subject in it is graded.
CREATE OR REPLACE PROCEDURE close_completed_enrolments()
    LANGUAGE plpgsql
AS $$
DECLARE
    v_closed INTEGER;
BEGIN
    WITH finished AS (
        SELECT es.id
        FROM enrolled_semesters es
        JOIN semesters_subjects ss ON ss.enrolled_semesters_id = es.id
        LEFT JOIN passed_subjects ps ON ps.enrolled_id = ss.id
        WHERE es.completed IS NULL
        GROUP BY es.id
        HAVING count(ss.id) > 0 AND count(ss.id) = count(ps.id)
    )
    UPDATE enrolled_semesters es
    SET completed   = now(),
        last_change = now()
    FROM finished f
    WHERE es.id = f.id;

    GET DIAGNOSTICS v_closed = ROW_COUNT;
    RAISE NOTICE 'close_completed_enrolments: closed % enrolment(s)', v_closed;
END;
$$;

-- Invalidates refresh tokens past their expiry.
CREATE OR REPLACE PROCEDURE expire_old_tokens()
    LANGUAGE plpgsql
AS $$
DECLARE
    v_expired INTEGER;
BEGIN
    UPDATE token
    SET is_valid = FALSE
    WHERE is_valid = TRUE AND expires_at < now();

    GET DIAGNOSTICS v_expired = ROW_COUNT;
    RAISE NOTICE 'expire_old_tokens: invalidated % token(s)', v_expired;
END;
$$;

-- Reminds students about subjects they are enrolled in without a signature.
CREATE OR REPLACE PROCEDURE notify_missing_signatures()
    LANGUAGE plpgsql
AS $$
DECLARE
    v_sent INTEGER;
BEGIN
    INSERT INTO notification (user_id, kind, message)
    SELECT es.user_id,
           'signature',
           format('Немате потпис по предметот %s за семестарот %s/%s.',
                  s.name, a.year, a.year + 1)
    FROM semesters_subjects ss
    JOIN enrolled_semesters es ON es.id = ss.enrolled_semesters_id
    JOIN subjects s            ON s.id  = ss.subjects_id
    JOIN active_semesters a    ON a.id  = es.semester_id
    WHERE ss.signature = FALSE
      AND es.completed IS NULL
      AND NOT EXISTS (
          SELECT 1 FROM notification n
          WHERE n.user_id = es.user_id
            AND n.kind = 'signature'
            AND n.message LIKE '%' || s.name || '%');

    GET DIAGNOSTICS v_sent = ROW_COUNT;
    RAISE NOTICE 'notify_missing_signatures: created % notification(s)', v_sent;
END;
$$;

CREATE OR REPLACE PROCEDURE refresh_statistics()
    LANGUAGE plpgsql
AS $$
BEGIN
    REFRESH MATERIALIZED VIEW CONCURRENTLY mv_subject_statistics;
    RAISE NOTICE 'refresh_statistics: mv_subject_statistics refreshed';
END;
$$;

-- One entry point for the scheduler (pg_cron, or the operating system).
CREATE OR REPLACE PROCEDURE run_nightly_maintenance()
    LANGUAGE plpgsql
AS $$
BEGIN
    CALL expire_old_tokens();
    CALL close_completed_enrolments();
    CALL notify_missing_signatures();
    CALL refresh_statistics();
    RAISE NOTICE 'run_nightly_maintenance: done';
END;
$$;

